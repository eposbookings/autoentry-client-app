CREATE TABLE `employer_settings` (
  `employer_id` integer PRIMARY KEY NOT NULL,
  `logo_url` text,
  `typical_pay_basis` text DEFAULT 'period' NOT NULL,
  `typical_annual_leave_days` real DEFAULT 28 NOT NULL,
